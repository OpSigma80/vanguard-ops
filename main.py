# ── Dashboard ─────────────────────────────────────────────────────────────────
@app.get("/", response_class=HTMLResponse)
async def dashboard(request: Request):
    try:
        with psycopg.connect(DATABASE_URL) as conn:
            with conn.cursor() as cur:

                cur.execute(
                    "SELECT id, full_name, email, phone, source, created_at "
                    "FROM leads ORDER BY id DESC LIMIT 10"
                )
                leads_raw = cur.fetchall()
                leads_db = [
                    (str(row[0]), row[1], row[2], row[3], row[4], row[5])
                    for row in leads_raw
                ]

                cur.execute(
                    "SELECT id, action, details FROM audit_logs ORDER BY id DESC LIMIT 15"
                )
                logs_raw = cur.fetchall()
                logs_db = [(str(row[0]), row[1], row[2]) for row in logs_raw]
                if not logs_db:
                    logs_db = [("0", "SYSTEM", "Engine Ready. Waiting for data...")]

                cur.execute("SELECT COUNT(*) FROM leads")
                total_res = cur.fetchone()
                total = total_res[0] if total_res else 0

                cur.execute("SELECT COUNT(DISTINCT source) FROM leads")
                nodes_res = cur.fetchone()
                nodes = nodes_res[0] if nodes_res and nodes_res[0] else 1

        context = {
            "leads": leads_db,
            "logs": logs_db,
            "stats": {
                "total_leads": total,
                "active_nodes": nodes,
                "system_status": "Operational",
                "uptime": "99.9%",
            },
            "version": "v1.1.1",
            "status": "ONLINE",
            "creator": "ISRAEL ROVIRA",
        }

        # Compatible con Starlette / FastAPI moderno
        return templates.TemplateResponse(
            request=request, name="index.html", context=context
        )

    except Exception as e:
        return HTMLResponse(content=f"<pre>DB Error: {e}</pre>", status_code=500)


# ── Crear lead ────────────────────────────────────────────────────────────────
@app.post("/api/v1/lead-intake", status_code=201)
async def lead_intake(lead: Lead):
    try:
        with psycopg.connect(DATABASE_URL) as conn:
            with conn.cursor() as cur:
                cur.execute(
                    "INSERT INTO leads (full_name, email, phone, source) "
                    "VALUES (%s, %s, %s, %s) RETURNING id",
                    (lead.full_name, lead.email, lead.phone, lead.source),
                )
                created = cur.fetchone()
                cur.execute(
                    "INSERT INTO audit_logs (action, details) VALUES (%s, %s)",
                    ("INGEST", f"New lead added: {lead.email}"),
                )
                conn.commit()
        return {
            "id": str(created[0]),
            "full_name": lead.full_name,
            "email": lead.email,
            "status": "success",
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


# ── Editar lead ───────────────────────────────────────────────────────────────
@app.patch("/api/v1/leads/{lead_id}")
async def update_lead(lead_id: str, lead: LeadUpdate):
    try:
        try:
            parsed_lead_id = uuid.UUID(lead_id)
        except ValueError:
            raise HTTPException(status_code=422, detail="Invalid lead UUID")

        with psycopg.connect(DATABASE_URL) as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT id FROM leads WHERE id = %s", (parsed_lead_id,))
                if not cur.fetchone():
                    raise HTTPException(
                        status_code=404, detail=f"Lead con ID {lead_id} no encontrado"
                    )

                cur.execute(
                    "UPDATE leads "
                    "SET full_name = %s, email = %s, phone = %s, source = %s "
                    "WHERE id = %s",
                    (
                        lead.full_name.strip(),
                        str(lead.email),
                        lead.phone.strip(),
                        lead.source.strip(),
                        parsed_lead_id,
                    ),
                )
                cur.execute(
                    "INSERT INTO audit_logs (action, details) VALUES (%s, %s)",
                    ("UPDATE", f"Updated lead ID: {lead_id}"),
                )
                conn.commit()

        return {"status": "updated", "id": lead_id}
    except HTTPException:
        raise
    except Exception as e:
        print(f"ERROR: Failed to update lead: {e}")
        raise HTTPException(status_code=500, detail="Internal server error")


# ── Eliminar registro de auditoría ────────────────────────────────────────────
@app.delete("/api/v1/audit-logs/{log_id}")
async def delete_audit_log(log_id: int):
    try:
        with psycopg.connect(DATABASE_URL) as conn:
            with conn.cursor() as cur:
                cur.execute(
                    "SELECT id FROM audit_logs WHERE id = %s",
                    (log_id,),
                )
                if not cur.fetchone():
                    raise HTTPException(
                        status_code=404,
                        detail=f"Registro de log con ID {log_id} no encontrado",
                    )

                cur.execute(
                    "DELETE FROM audit_logs WHERE id = %s",
                    (log_id,),
                )
                conn.commit()

        return {"status": "deleted", "id": log_id}
    except HTTPException:
        raise
    except Exception as e:
        print(f"ERROR: Failed to delete audit log: {e}")
        raise HTTPException(status_code=500, detail="Internal server error")


